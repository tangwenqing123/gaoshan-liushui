/**
 * 根据用户选择的金句计算六维得分
 * @param {Array} picks - 用户选中的金句数组
 * @returns {Object} 六维得分（0-100）
 */
function calcDimensions(picks) {
  const raw = { "才情": 0, "旷达": 0, "深情": 0, "孤高": 0, "谋略": 0, "通透": 0 };
  picks.forEach(q => {
    const map = CATEGORY_DIMENSION_MAP[q.category] || {};
    DIMENSION_NAMES.forEach(d => {
      raw[d] += (map[d] || 0);
    });
  });
  // 归一化到 0-100（每句金句最大贡献4分，N句最大4N）
  const maxRaw = picks.length * 3;
  const result = {};
  DIMENSION_NAMES.forEach(d => {
    result[d] = Math.min(100, Math.round(raw[d] / maxRaw * 100));
  });
  return result;
}

/**
 * 根据六维得分生成维度解读文案
 * @param {Object} dims - 六维得分
 * @returns {Array} 解读文案数组
 */
function getDimensionInsights(dims) {
  return DIMENSION_NAMES.map(name => {
    const score = dims[name];
    const meta = DIMENSION_META[name];
    let level, desc;
    if (score >= 75) { level = "high"; desc = meta.high; }
    else if (score >= 40) { level = "mid"; desc = meta.mid; }
    else { level = "low"; desc = meta.low; }
    return { name, score, level, icon: meta.icon, desc };
  });
}

